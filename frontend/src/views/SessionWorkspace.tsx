import { useEffect, useRef, useState } from 'react';
import { useParams } from 'react-router-dom';
import { listCandidates, getSession, listArrangements, getArrangement, dismissCandidate, getGenres } from '../services/api';
import type { SessionSummary, ArrangementDetail, GenreSummary } from '../services/api';
import { useCandidateStore } from '../stores/candidateStore';
import { useArrangementStore } from '../stores/arrangementStore';
import { useGenerationFlow } from '../hooks/useGenerationFlow';
import { useRealizationFlow } from '../hooks/useRealizationFlow';
import { useMutationFlow } from '../hooks/useMutationFlow';
import CandidateCard from '../components/CandidateCard';
import PromptBar from '../components/PromptBar';
import TokenUsagePanel from '../components/TokenUsagePanel';
import ArrangementList from '../components/ArrangementList';
import ArrangementDetailView from '../components/ArrangementDetail';
import LineageTree from '../components/LineageTree';
import MutateModal from '../components/MutateModal';
import ExportModal from '../components/ExportModal';
import ComparisonView from '../components/ComparisonView';
import SessionHistory from '../components/SessionHistory';
import { useExportStore } from '../stores/exportStore';
import { useCan } from '../stores/capabilitiesStore';
import { useDocumentTitle } from '../hooks/useDocumentTitle';
import * as audioEngine from '../services/audioEngine';

export default function SessionWorkspace() {
  const { id } = useParams<{ id: string }>();
  const [session, setSession] = useState<SessionSummary | null>(null);
  const canLineage = useCan('lineage');
  const canSessionHistory = useCan('session_history');
  useDocumentTitle(session?.prompt ?? 'Session');
  const [prompt, setPrompt] = useState('');
  const [genres, setGenres] = useState<GenreSummary[]>([]);
  const [genre, setGenre] = useState('');
  const [musicalKey, setMusicalKey] = useState('C');
  const [musicalMode, setMusicalMode] = useState('major');
  const [viewMode, setViewMode] = useState<'generation' | 'realization'>('generation');
  const [dismissedIds, setDismissedIds] = useState<Set<string>>(new Set());
  const [showExportModal, setShowExportModal] = useState(false);
  const [showComparison, setShowComparison] = useState(false);
  const [comparisonArrangements, setComparisonArrangements] = useState<Map<string, ArrangementDetail>>(new Map());

  const { candidates, setCandidates, selectedForComparison, toggleComparison } = useCandidateStore();
  const { fetchPackages } = useExportStore();
  const arrangementStore = useArrangementStore();

  const generation = useGenerationFlow(id);
  const realization = useRealizationFlow(id);
  const mutation = useMutationFlow(id);

  const loading = generation.loading || realization.loading;
  const currentNode = generation.currentNode || realization.currentNode;

  useEffect(() => {
    if (!id) return;

    const load = async () => {
      try {
        const [s, res] = await Promise.all([
          getSession(id),
          listCandidates(id),
        ]);
        setSession(s);
        setCandidates(res.items);
        if (s.prompt) setPrompt(s.prompt);
        if (s.genre) setGenre(s.genre);
        if (s.key) setMusicalKey(s.key);
        if (s.musical_mode) setMusicalMode(s.musical_mode);
      } catch { /* ignore */ }
    };
    load();
  }, [id, setCandidates]);

  // Auto-generate when the session has loaded with a prompt but no candidates.
  // Gate on `session` so we never fire before the loader resolves, and derive
  // the effective genre from the loaded session to avoid a race with the
  // genre-list seeder below (which may transiently set a different genre).
  const hasAutoGenerated = useRef(false);
  useEffect(() => {
    if (
      session &&
      session.prompt &&
      prompt &&
      candidates.length === 0 &&
      !generation.loading &&
      !hasAutoGenerated.current
    ) {
      hasAutoGenerated.current = true;
      generation.generate(
        prompt,
        session.genre ?? genre,
        session.key ?? musicalKey,
        session.musical_mode ?? musicalMode,
      );
    }
    // `generation` is intentionally excluded — the ref-gated `generate()` call
    // should fire once per session load, not on every render-induced identity
    // change of the generation flow object.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [session, prompt, genre, candidates.length, generation.loading]);

  // Fetch the known genres for the in-session re-generate picker. We do NOT
  // force `items[0]` here: that could disagree with the server's empty-genre
  // fallback (e.g. "dream_pop") and make the picker show one genre while the
  // persisted round used another. The session loader seeds `genre` from the
  // session when it carries one; otherwise we leave it unset and let the round
  // resolve the genre server-side.
  useEffect(() => {
    getGenres()
      .then((items) => setGenres(items))
      .catch(() => { /* ignore — picker just stays empty */ });
  }, []);

  const handleGenerate = () =>
    generation.generate(prompt, session?.genre ?? genre, musicalKey, musicalMode);

  const handleDismiss = async (candidateId: string) => {
    try {
      await dismissCandidate(candidateId);
    } catch {
      // API call failed — still dismiss locally
    }
    setDismissedIds(prev => new Set(prev).add(candidateId));
  };

  // Filter out dismissed candidates entirely
  const sortedCandidates = candidates.filter(c => !dismissedIds.has(c.candidate_id));

  const handleRealize = async (candidateId: string) => {
    const result = await realization.realize(candidateId);
    if (result.status === 'error') {
      generation.setError(result.error);
    } else {
      setViewMode('realization');
    }
  };

  const handleMutateSubmit = async (guidance: string) => {
    const err = await mutation.submit(guidance);
    if (err) generation.setError(err);
  };

  const loadComparisonArrangements = async (ids: string[]) => {
    const loaded = new Map<string, ArrangementDetail>();
    for (const candidateId of ids) {
      // Reuse already-loaded arrangements to avoid redundant fetches
      const existing = comparisonArrangements.get(candidateId);
      if (existing) {
        loaded.set(candidateId, existing);
        continue;
      }
      try {
        const summaries = await listArrangements(candidateId);
        if (summaries.length > 0) {
          const detail = await getArrangement(summaries[0].id);
          loaded.set(candidateId, detail);
        }
      } catch {
        // skip failed loads
      }
    }
    setComparisonArrangements(loaded);
  };

  const handleCompare = async () => {
    await loadComparisonArrangements(selectedForComparison);
    setShowComparison(true);
  };

  // Auto-refresh comparison view when selections change while it's open.
  // Use a stable string key so we don't re-fire on every parent re-render,
  // and intentionally omit non-content deps (loadComparisonArrangements,
  // showComparison) — adding them would cause cascading reloads.
  const selectedKey = selectedForComparison.join(',');
  useEffect(() => {
    if (showComparison && selectedForComparison.length >= 2) {
      loadComparisonArrangements(selectedForComparison);
    } else if (showComparison && selectedForComparison.length < 1) {
      setShowComparison(false);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [selectedKey]);

  return (
    <div data-testid="session-workspace" className="max-w-6xl mx-auto p-8 flex flex-col gap-5">
      {/* Header */}
      <div className="flex items-center gap-4">
        <div className="flex-1 min-w-0">
          <h1 data-testid="session-title" className="text-lg font-semibold truncate" style={{ color: 'var(--text-primary)' }}>
            {session?.prompt || <span className="font-mono text-sm" style={{ color: 'var(--text-muted)' }}>{id}</span>}
          </h1>
          {session && (
            <p className="text-xs font-mono" style={{ color: 'var(--text-muted)' }}>
              {session.mode} &middot; {session.status}{session.genre ? ` \u00b7 ${session.genre}` : ''}
            </p>
          )}
        </div>
        {candidates.length > 0 && (
          <button
            onClick={() => {
              fetchPackages(id!);
              setShowExportModal(true);
            }}
            className="rounded border px-3 py-1 text-sm transition-colors"
            style={{
              color: viewMode === 'realization' ? 'var(--accent-primary)' : 'var(--text-muted)',
              borderColor: viewMode === 'realization' ? 'var(--accent-primary-dim)' : 'var(--border-default)',
            }}
            title={viewMode === 'generation' ? 'View arrangements first to export MIDI' : 'Export arrangements as MIDI/JSON'}
          >
            Export
          </button>
        )}
      </div>

      {/* Prompt bar */}
      <div data-testid="prompt-section" className="rounded-lg p-4" style={{ background: 'var(--surface-2)', border: '1px solid var(--border-subtle)' }}>
        {currentNode?.startsWith('mutation_completed') && (() => {
          const parts = currentNode.split(':');
          return (
            <div className="text-xs font-mono mb-1" style={{ color: 'var(--accent-secondary)' }}>
              Round {parts[1]} — {parts[2]} mutation{parts[2] === '1' ? '' : 's'} applied, re-evaluating...
            </div>
          );
        })()}
        <PromptBar
          prompt={prompt}
          onPromptChange={setPrompt}
          onGenerate={handleGenerate}
          loading={loading}
          currentNode={currentNode}
          genre={genre}
          onGenreChange={setGenre}
          genres={genres}
          musicalKey={musicalKey}
          onKeyChange={setMusicalKey}
          musicalMode={musicalMode}
          onMusicalModeChange={setMusicalMode}
        />
      </div>

      {/* Token usage */}
      <TokenUsagePanel />

      {/* Error */}
      {generation.error && (
        <div data-testid="error-message" role="alert" aria-live="assertive" className="rounded-lg px-4 py-3 text-sm" style={{ background: 'var(--danger-bg)', border: '1px solid var(--danger-border)', color: 'var(--danger-text)' }}>
          {generation.error}
        </div>
      )}

      {viewMode === 'realization' ? (
        <>
          <button
            data-testid="back-to-progressions"
            onClick={() => {
              setViewMode('generation');
              audioEngine.stop();
              arrangementStore.reset();
            }}
            className="inline-flex items-center gap-1.5 self-start text-sm font-medium mb-3 px-3 py-1.5 rounded-md transition-colors"
            style={{ color: 'var(--text-secondary)', background: 'var(--surface-1)', border: '1px solid var(--border-default)' }}
          >
            &larr; Back to progressions
          </button>
          <div className="flex flex-1 min-h-0 rounded-lg overflow-hidden" style={{ border: '1px solid var(--border-subtle)' }}>
            <ArrangementList
              arrangements={arrangementStore.arrangements}
              candidates={candidates}
              selectedId={arrangementStore.selectedArrangementId}
              onSelect={realization.selectArrangement}
              genre={session?.genre || 'dream_pop'}
              finalSelection={useCandidateStore.getState().finalSelection}
            />
            <ArrangementDetailView
              arrangement={arrangementStore.selectedDetail}
              genre={session?.genre || 'dream_pop'}
            />
          </div>
        </>
      ) : (
        <>
          {/* Mutation in-flight banner */}
          {mutation.inFlight && (
            <div data-testid="mutation-spinner" className="flex items-center gap-3 px-4 py-3 rounded-lg" style={{ background: 'var(--accent-secondary-dim)', border: '1px solid var(--accent-secondary)' }}>
              <div className="w-4 h-4 border-2 rounded-full animate-spin shrink-0" style={{ borderColor: 'var(--accent-secondary)', borderTopColor: 'transparent' }} />
              <div>
                <span className="text-sm" style={{ color: 'var(--accent-secondary)' }}>
                  Mutating candidate {mutation.inFlightLabel}
                </span>
                <span className="text-xs font-mono ml-2" style={{ color: 'var(--text-muted)' }}>
                  {mutation.inFlightChords.join(' \u2192 ')}
                </span>
              </div>
            </div>
          )}

          {/* Mutation result banner */}
          {mutation.lastResult && !mutation.inFlight && (
            <div className="rounded-lg px-4 py-3" style={{ background: 'var(--accent-secondary-dim)', border: '1px solid var(--accent-secondary)' }}>
              <div className="flex items-center justify-between mb-2">
                <span className="text-sm font-medium" style={{ color: 'var(--accent-secondary)' }}>
                  Mutation applied to {mutation.inFlightLabel}
                </span>
                <button onClick={mutation.dismissResult} className="text-xs" style={{ color: 'var(--text-muted)' }}>dismiss</button>
              </div>
              <div className="text-xs font-mono mb-1" style={{ color: 'var(--text-primary)' }}>
                {mutation.lastResult.mutated_chord_symbols.join(' \u2192 ')}
              </div>
              {mutation.lastResult.mutations.map((m, i) => (
                <div key={i} className="text-xs flex gap-2" style={{ color: 'var(--text-secondary)' }}>
                  <span className="font-mono" style={{ color: 'var(--accent-secondary)' }}>{m.operation}</span>
                  {m.original_value && m.new_value && (
                    <span>
                      <span style={{ color: 'var(--score-low)' }}>{m.original_value}</span>
                      {' \u2192 '}
                      <span style={{ color: 'var(--score-high)' }}>{m.new_value}</span>
                    </span>
                  )}
                  {m.description && <span style={{ color: 'var(--text-muted)' }}>{m.description}</span>}
                </div>
              ))}
            </div>
          )}

          {candidates.length > 0 ? (
            <div>
              <div className="flex items-center justify-between mb-3">
                <h2 data-testid="candidate-count" className="text-xs font-medium uppercase tracking-wider" style={{ color: 'var(--text-muted)' }}>
                  {candidates.length} candidate{candidates.length !== 1 ? 's' : ''}
                </h2>
                {selectedForComparison.length > 0 && !showComparison && (
                  <button
                    onClick={handleCompare}
                    disabled={selectedForComparison.length < 2}
                    className="rounded-md px-4 py-1.5 text-sm font-medium transition-colors disabled:opacity-40"
                    style={{ background: 'var(--role-experimental)', color: '#fff' }}
                  >
                    {selectedForComparison.length < 2
                      ? `Compare (select ${2 - selectedForComparison.length} more)`
                      : `Compare ${selectedForComparison.length} candidates`}
                  </button>
                )}
              </div>
              <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
                {sortedCandidates.map((c, i) => (
                  <div
                    key={c.candidate_id}
                    className="card-animated"
                    style={{ animationDelay: `${i * 50}ms` }}
                  >
                    <div>
                      <CandidateCard
                        candidate={c}
                        index={i}
                        onRealize={dismissedIds.has(c.candidate_id) ? undefined : handleRealize}
                        onMutate={dismissedIds.has(c.candidate_id) ? undefined : mutation.openModal}
                        onDismiss={c.metadata?.mutated_from ? handleDismiss : undefined}
                        onClick={dismissedIds.has(c.candidate_id) ? undefined : () => handleRealize(c.candidate_id)}
                        onCompare={dismissedIds.has(c.candidate_id) ? undefined : toggleComparison}
                        isSelectedForComparison={selectedForComparison.includes(c.candidate_id)}
                        parentLabel={(() => {
                          const parentId = c.metadata?.mutated_from as string | undefined;
                          if (!parentId) return undefined;
                          const parentIdx = sortedCandidates.findIndex(p => p.candidate_id === parentId);
                          return parentIdx >= 0 ? String.fromCharCode(65 + parentIdx) : undefined;
                        })()}
                      />
                    </div>
                  </div>
                ))}
              </div>
            </div>
          ) : (
            !loading && (
              <div data-testid="empty-state" className="rounded-lg p-8 text-center text-sm" style={{ background: 'var(--surface-2)', border: '1px solid var(--border-subtle)', color: 'var(--text-muted)' }}>
                No candidates yet. Enter a prompt above and click Generate to start exploring.
              </div>
            )
          )}

          {canLineage && (
            <LineageTree
              candidates={candidates}
              onSelectCandidate={(cid) => handleRealize(cid)}
            />
          )}

          {/* Comparison view */}
          {showComparison && (
            <ComparisonView
              sessionId={id!}
              genre={session?.genre || 'dream_pop'}
              arrangements={comparisonArrangements}
              candidateLabels={Object.fromEntries(
                sortedCandidates.map((c, i) => [c.candidate_id, String.fromCharCode(65 + i)])
              )}
              onClose={() => setShowComparison(false)}
            />
          )}

          {loading && candidates.length === 0 && (
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
              {[1, 2, 3].map((i) => (
                <div key={i} className="rounded-lg p-4 h-48 animate-pulse" style={{ background: 'var(--surface-2)', border: '1px solid var(--border-subtle)' }} />
              ))}
            </div>
          )}
        </>
      )}

      {/* Mutation modal */}
      {mutation.mutatingCandidate && (
        <MutateModal
          candidateId={mutation.mutatingCandidate.candidate_id}
          chordSymbols={mutation.mutatingCandidate.chord_symbols}
          onSubmit={handleMutateSubmit}
          onClose={mutation.closeModal}
        />
      )}

      {/* Export modal — shows arrangements when in realization view, progressions otherwise */}
      {showExportModal && (
        <ExportModal
          sessionId={id!}
          candidates={(() => {
            if (viewMode === 'realization' && arrangementStore.arrangements.length > 0) {
              // In arrangement view: export the actual arrangements (which have voicing + bass data)
              return arrangementStore.arrangements.map((a, i) => ({
                id: a.id,
                label: `Arrangement ${i + 1}`,
                role: a.status === 'selected' ? 'best' : '',
                chords: [a.rationale],
              }));
            }
            // In generation view: show progression candidates (export needs arrangements though)
            const finalSelection = useCandidateStore.getState().finalSelection;
            const roles = finalSelection?.selection_roles ?? {};
            return candidates.map((c, i) => ({
              id: c.candidate_id,
              label: `Candidate ${i + 1}`,
              role: roles[c.candidate_id] ?? '',
              chords: c.chord_symbols,
            }));
          })()}
          onClose={() => setShowExportModal(false)}
        />
      )}

      {/* Session history */}
      {id && canSessionHistory && <SessionHistory sessionId={id} />}
    </div>
  );
}
